# Operator aritmatika
a = 4
b = 2
c = a + b    # Penjumlahan
d = a - b    # Pengurangan
e = a * b    # Perkalian
f = a / b    # Pembagian
g = a % b    # Modulus
h = a ** b   # Eksponensial

print(c) # 6
print(d) # 2
print(e) # 8
print(f) # 2.0
print(g) # 0
print(h) # 16


# Operator perbandingan
a = 3
b = 5
c = a == b   # sama dengan
d = a != b   # tidak sama dengan
e = a < b    # lebih kecil
f = a <= b   # lebih kecil sama dengan
g = a > b    # lebih besar
h = a >= b   # lebih besar sama dengan

print(c) # False
print(d) # True
print(e) # True
print(f) # True
print(g) # False
print(h) # False


